"""Build data/recipes.js from the recipe workbook.

Usage:  python3 scripts/build_recipes.py path/to/Συνταγές.xlsx

Expects a sheet «Συνταγές» (one row per recipe) and, optionally, a sheet «Υλικά»
(one row per ingredient). Columns are found by header name, so their order may change.
"""
import json, sys, re, unicodedata, pathlib
import openpyxl

def norm(s):
    s = unicodedata.normalize('NFD', str(s or '').lower())
    return ''.join(c for c in s if unicodedata.category(c) != 'Mn').strip()

def finder(header):
    h = [norm(x) for x in header]
    def col(*pats, exclude=None):
        for i, name in enumerate(h):
            if any(re.search(p, name) for p in pats) and not (exclude and re.search(exclude, name)):
                return i
        return None
    return col

def main(path):
    wb = openpyxl.load_workbook(path, data_only=True)
    ws = wb['Συνταγές'] if 'Συνταγές' in wb.sheetnames else wb.worksheets[0]
    rows = list(ws.iter_rows(values_only=True))
    col = finder(rows[0])
    C = dict(id=col(r'^α/α'), title=col(r'^τιτλ'), cats=col(r'κατηγορ'), serv=col(r'μεριδ'),
             ing=col(r'^υλικ'), steps=col(r'^εκτελεσ'), nutr=col(r'διατροφικ'),
             url=col(r'συνδεσμ', r'^url'), code=col(r'^κωδικ'), src=col(r'^πηγη$', r'^source$'),
             acct=col(r'λογαριασμ'), kind=col(r'ειδοσ εκτελεσ'))
    get = lambda r, k: (r[C[k]] if C[k] is not None and C[k] < len(r) else None)
    recs, by_code = [], {}
    for r in rows[1:]:
        if not get(r, 'title'):
            continue
        rec = {
            'id': get(r, 'id'), 'title': str(get(r, 'title')).strip(),
            'cats': [c.strip() for c in str(get(r, 'cats') or '').split(',') if c.strip()],
            'serv': get(r, 'serv'), 'steps': get(r, 'steps'), 'nutr': get(r, 'nutr'),
            'url': get(r, 'url'), 'code': str(get(r, 'code') or get(r, 'id')),
            'src': get(r, 'src') or '', 'acct': get(r, 'acct'), 'kind': get(r, 'kind'), 'ing': [],
        }
        # ingredients from the recipe row (bullets, «Ομάδα:» headings) — replaced below if a «Υλικά» sheet exists
        g = None
        for line in str(get(r, 'ing') or '').split('\n'):
            t = line.strip()
            if not t:
                continue
            m = re.match(r'^[•\-*]\s*(.+)$', t)
            if m: rec['ing'].append({'t': m.group(1), 'g': g})
            elif t.endswith(':'): g = t[:-1]
            else: rec['ing'].append({'t': t, 'g': g})
        recs.append(rec); by_code[rec['code']] = rec
    if 'Υλικά' in wb.sheetnames:
        irows = list(wb['Υλικά'].iter_rows(values_only=True))
        icol = finder(irows[0])
        ci, cg, ct = icol(r'^κωδικ'), icol(r'ομαδα'), icol(r'^υλικο$')
        seen = set()
        for r in irows[1:]:
            rec = by_code.get(str(r[ci])) if ci is not None else None
            if not rec or not r[ct]:
                continue
            if rec['code'] not in seen:
                rec['ing'] = []; seen.add(rec['code'])
            rec['ing'].append({'t': str(r[ct]).strip(), 'g': r[cg] if cg is not None else None})
    recs = [r for r in recs if r['ing']]
    out = pathlib.Path(__file__).resolve().parent.parent / 'data' / 'recipes.js'
    js = json.dumps(recs, ensure_ascii=False, separators=(',', ':')).replace('</', '<\\/')
    out.write_text(f'// Built-in recipes — generated by scripts/build_recipes.py from {pathlib.Path(path).name}. Do not edit by hand.\nconst BUILTIN_RECIPES = {js};\n', encoding='utf-8')
    srcs = {}
    for r in recs: srcs[r['src']] = srcs.get(r['src'], 0) + 1
    print(f'{len(recs)} recipes, {sum(len(r["ing"]) for r in recs)} ingredient lines -> {out}')
    for k, v in sorted(srcs.items(), key=lambda x: -x[1]): print(f'  {v:5d}  {k}')

if __name__ == '__main__':
    main(sys.argv[1])
